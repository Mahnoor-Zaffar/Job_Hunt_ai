async def seed():
    factory = get_session_factory()
    async with factory() as session:
        existing = list((await session.execute(select(Job.id, Job.fingerprint))).all())
        existing_fps = {r.fingerprint for r in existing}
        print(f"Existing jobs in DB: {len(existing)}")

        count = 0
        for data in SEED_JOBS:
            raw = f"{data['title'].lower().strip()}|{data['company'].lower().strip()}|{data.get('location', 'remote').lower().strip()}|{data['url'].strip()}"
            fp = hashlib.sha256(raw.encode()).hexdigest()
            if fp in existing_fps:
                continue

            job = Job(
                title=data["title"],
                company=data["company"],
                location=data.get("location", "Remote"),
                city=data.get("city"),
                country=data.get("country"),
                is_remote=data.get("is_remote", False),
                remote_type=data.get("remote_type", "onsite"),
                description=data.get("description"),
                requirements=data.get("requirements"),
                url=data["url"],
                apply_url=data.get("apply_url"),
                source=data["source"],
                source_id=data["source_id"],
                salary_min=data.get("salary_min"),
                salary_max=data.get("salary_max"),
                currency=data.get("currency"),
                employment_type=data.get("employment_type"),
                experience_level=data.get("experience_level"),
                skills=data.get("skills", []),
                posted_at=data.get("posted_at"),
                fingerprint=fp,
                status="active",
            )
            session.add(job)
            count += 1

        await session.commit()
        print(f"Seeded {count} new jobs")
        print(f"Total active jobs: {await session.scalar(select(Job).where(Job.status == 'active').count())}")


asyncio.run(seed())
